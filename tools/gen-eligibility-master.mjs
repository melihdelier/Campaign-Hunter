// Sunucu tarafı (kalite kapısı + crawler çift-yazımı) için ana veri kodlarını paketli profil kataloğundan üretir.
// Kullanım: node tools/gen-eligibility-master.mjs  → server/eligibility_master.v1.json
// Birebir aynılık web/test-eligibility.mjs ve server testlerinde doğrulanır.
import { writeFileSync } from 'node:fs';
import { BUNDLED_PROFILE_CATALOG as C } from '../web/profile-catalog.js';

export function eligibilityMaster(catalog = C) {
  return {
    schema: 'eligibility-master-codes', schemaVersion: 1,
    note: 'Codes the catalog quality guard accepts in eligibility rules, plus the legacy engine-label → option-code map used by the crawler dual-write. Generated by tools/gen-eligibility-master.mjs from web/profile-catalog.js (= migration seeds). Do not edit by hand.',
    banks: catalog.banks.map(b => b.code),
    cardProducts: catalog.cardProducts.map(p => ({ code: p.code, bankCode: p.bankCode })),
    cardFamilies: (catalog.cardFamilies || []).map(f => ({ code: f.code, bankCode: f.bankCode, members: [...f.members], membershipComplete: f.membershipComplete === true })),
    dimensions: catalog.dimensions.map(d => ({
      code: d.code, options: d.options.map(o => o.code),
      engineBinding: d.engineBinding, cardCodes: [...(d.cardCodes || [])],
      engineLabels: Object.fromEntries(d.options.map(o => [o.code, o.engineLabel || o.label])),
    })),
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('../server/eligibility_master.v1.json', import.meta.url), JSON.stringify(eligibilityMaster(), null, 2) + '\n');
  console.log('server/eligibility_master.v1.json written');
}
